    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        try {
    // Mengambil nilai dari inputan
    double presensi = Double.parseDouble(txtPresensi.getText());
    double tugas = Double.parseDouble(txtTugas.getText());
    double uts = Double.parseDouble(txtUts.getText());
    double uas = Double.parseDouble(txtUas.getText());

    // Berdasarkan gambar, perhitungan bobot standarnya adalah:
    // Presensi 10% (maks 14 pertemuan), Tugas 20%, UTS 30%, UAS 40%
    double nilaiPresensi = (presensi / 14.0) * 100.0;
    double nilaiAkhir = (nilaiPresensi * 0.10) + (tugas * 0.20) + (uts * 0.30) + (uas * 0.40);

    // Menentukan Grade
    String grade;
    if (nilaiAkhir >= 80) {
        grade = "A";
    } else if (nilaiAkhir >= 70) {
        grade = "B";
    } else if (nilaiAkhir >= 60) {
        grade = "C";
    } else if (nilaiAkhir >= 50) {
        grade = "D";
    } else {
        grade = "E";
    }

    // Menampilkan hasil dengan format 2 angka di belakang koma
    txtNilaiAkhir.setText(String.format(java.util.Locale.US, "%.2f", nilaiAkhir));
    txtGrade.setText(grade);

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Harap masukkan data angka yang valid pada bobot penilaian!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnProsesActionPerformed

